@app.cell
def _(blob_features, euclidean_distances, np, plt):
    K_RANGE = range(1, 11)
    ELBOW_CONVERGENCE_THRESHOLD = 1.0

    _wcss_values = []

    for _k in K_RANGE:
        np.random.seed(42)

        _random_rows = np.random.choice(
            a=len(blob_features),
            size=_k,
            replace=False,
        )
        _centers = blob_features[_random_rows].copy()

        _delta_wcss = np.inf
        _best_wcss = None

        while _delta_wcss > ELBOW_CONVERGENCE_THRESHOLD:
            _center_distances = euclidean_distances(
                blob_features,
                _centers,
            )
            _assignments = np.argmin(_center_distances, axis=1)

            _wcss = 0
            for _cluster_id in np.unique(_assignments):
                _mask = _assignments == _cluster_id
                _distances = euclidean_distances(
                    blob_features[_mask],
                    _centers[_cluster_id].reshape(1, -1),
                )
                _wcss += (_distances.flatten() ** 2).sum()

            for _cluster_id in np.unique(_assignments):
                _mask = _assignments == _cluster_id
                _centers[_cluster_id] = blob_features[_mask].mean(axis=0)

            if _best_wcss is None:
                _delta_wcss = _wcss
            else:
                _delta_wcss = _best_wcss - _wcss
            _best_wcss = _wcss

        _wcss_values.append(_best_wcss)

    _fig, _ax = plt.subplots(figsize=(8, 5))
    _ax.plot(
        list(K_RANGE),
        _wcss_values,
        marker="o",
        color="steelblue",
        linewidth=2,
    )
    _ax.set_xlabel("Number of Clusters (k)")
    _ax.set_ylabel("WCSS")
    _ax.set_title("Elbow Method — WCSS vs. k")
    _ax.set_xticks(list(K_RANGE))

    plt.tight_layout()
    plt.show()
    return


