@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## K-Means Algorithm

    K-Means partitions $n$ observations into $k$ clusters by iteratively minimizing the
    **within-cluster sum of squares (WCSS)**:

    $$
    \text{WCSS} = \sum_{j=1}^{k} \sum_{\mathbf{x}_i \in C_j} \| \mathbf{x}_i - \boldsymbol{\mu}_j \|^2
    $$

    where $C_j$ is the set of points assigned to cluster $j$ and $\boldsymbol{\mu}_j$ is
    the centroid of that cluster.

    **Steps:**

    1. Randomly select $k$ data points as initial centroids.
    2. **Assign** each point to the nearest centroid.
    3. **Update** each centroid to be the mean of its assigned points.
    4. Repeat steps 2–3 until the change in WCSS falls below a threshold.
    """)
    return


@app.cell
def _(blob_features, euclidean_distances, np, plt, sns):
    N_CLUSTERS = 5
    CONVERGENCE_THRESHOLD = 1.0

    np.random.seed(42)

    _random_rows = np.random.choice(
        a=len(blob_features),
        size=N_CLUSTERS,
        replace=False,
    )
    _centers = blob_features[_random_rows].copy()

    _delta_wcss = np.inf
    _best_wcss = None

    while _delta_wcss > CONVERGENCE_THRESHOLD:
        _center_distances = euclidean_distances(
            blob_features,
            _centers,
        )
        blob_cluster_assignments = np.argmin(_center_distances, axis=1)

        _wcss = 0
        for _cluster_id in np.unique(blob_cluster_assignments):
            _mask = blob_cluster_assignments == _cluster_id
            _distances = euclidean_distances(
                blob_features[_mask],
                _centers[_cluster_id].reshape(1, -1),
            )
            _wcss += (_distances.flatten() ** 2).sum()

        for _cluster_id in np.unique(blob_cluster_assignments):
            _mask = blob_cluster_assignments == _cluster_id
            _centers[_cluster_id] = blob_features[_mask].mean(axis=0)

        if _best_wcss is None:
            _delta_wcss = _wcss
        else:
            _delta_wcss = _best_wcss - _wcss
        _best_wcss = _wcss

    _fig, _ax = plt.subplots(figsize=(8, 5))

    sns.scatterplot(
        x=blob_features[:, 0],
        y=blob_features[:, 1],
        hue=blob_cluster_assignments,
        edgecolor="k",
        alpha=0.75,
        ax=_ax,
    )
    _ax.set_xlabel("Feature 1")
    _ax.set_ylabel("Feature 2")
    _ax.set_title("K-Means on Blob Data (k=5)")
    _ax.legend(
        title="Cluster",
        bbox_to_anchor=(1.01, 1.01),
        loc="upper left",
    )

    plt.tight_layout()
    plt.show()
    return (blob_cluster_assignments,)


